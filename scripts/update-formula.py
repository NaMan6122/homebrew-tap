#!/usr/bin/env python3
"""Regenerate Formula/anvaya.rb from the Anvaya release channel pointer.

    scripts/update-formula.py                  # fetch the beta channel from GitHub
    scripts/update-formula.py --channel-file channels/beta.tsv

The channel TSV is the same file the curl installer reads, so the formula can
never point at a different artifact than the installer does. Columns:
    kind  target  version  sha256  size  url
Only `bundle` rows are used: Homebrew installs anv and mind-daemon together.
"""
import argparse, os, sys, urllib.request

CHANNEL_URL = "https://raw.githubusercontent.com/NaMan6122/Anvaya/main/channels/{channel}.tsv"
TARGETS = {
    "mac_arm": "aarch64-apple-darwin",
    "linux_arm": "aarch64-unknown-linux-gnu",
    "linux_intel": "x86_64-unknown-linux-gnu",
}

TEMPLATE = """\
# Generated by scripts/update-formula.py from the Anvaya {channel} channel.
# Do not edit by hand; run the script (or the "Update formula" workflow).
class Anvaya < Formula
  desc "Agentic terminal coding assistant, bundled with its Mind memory daemon"
  homepage "https://anvayahq.com"

  on_macos do
    depends_on arch: :arm64

    url "{mac_arm[url]}"
    sha256 "{mac_arm[sha]}"
  end

  on_linux do
    on_arm do
      url "{linux_arm[url]}"
      sha256 "{linux_arm[sha]}"
    end

    on_intel do
      url "{linux_intel[url]}"
      sha256 "{linux_intel[sha]}"
    end
  end

  def install
    # anv finds mind-daemon next to itself, so both must land in the same bin.
    bin.install "bin/anv", "bin/mind-daemon"
    pkgshare.install "bundle.json" if File.exist?("bundle.json")
  end

  def caveats
    <<~EOS
      anv starts mind-daemon on demand, per project. Both were installed together;
      do not upgrade one without the other.

      Linux needs glibc 2.39 or newer (Ubuntu 24.04+, Debian 13+, Fedora 40+).
      The macOS binary is ad-hoc signed, not notarized; Homebrew installs it
      without the quarantine flag, so it runs without a Gatekeeper prompt.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/anv --version")
    assert_match "mind-daemon", shell_output("#{{bin}}/mind-daemon --version")
    assert_equal (bin/"anv").dirname, (bin/"mind-daemon").dirname
  end
end
"""

def read_channel(args):
    if args.channel_file:
        return open(args.channel_file).read()
    url = CHANNEL_URL.format(channel=args.channel)
    with urllib.request.urlopen(url, timeout=30) as r:
        return r.read().decode()

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--channel", default="beta")
    ap.add_argument("--channel-file")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "Formula", "anvaya.rb"))
    args = ap.parse_args()

    rows = {}
    for line in read_channel(args).splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        kind, target, version, sha, size, url = line.split("\t")[:6]
        if kind == "bundle":
            rows[target] = {"version": version, "sha": sha, "url": url}

    ctx, versions = {}, set()
    for key, target in TARGETS.items():
        if target not in rows:
            sys.exit(f"channel has no bundle for {target}")
        ctx[key] = rows[target]
        versions.add(rows[target]["version"])
        if not rows[target]["url"].startswith("https://"):
            sys.exit(f"refusing non-https url for {target}: {rows[target]['url']}")
    if len(versions) != 1:
        sys.exit(f"bundles disagree on version: {sorted(versions)}")

    versions.pop()  # all bundles agree; Homebrew reads the version from the URL
    text = TEMPLATE.format(channel=args.channel, **ctx)
    out = os.path.abspath(args.out)
    old = open(out).read() if os.path.exists(out) else ""
    if old == text:
        print("formula already up to date")
        return
    with open(out, "w") as f:
        f.write(text)
    print(f"wrote {out}")

main()
